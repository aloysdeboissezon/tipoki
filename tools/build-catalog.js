// Builds js/catalog.js: the small list (title, subject, sessions...) of the built-in quizzes that load on demand.
// Usage: node tools/build-catalog.js          rewrites js/catalog.js
//        node tools/build-catalog.js --check  exits 1 when js/catalog.js is out of date (run it after editing a bank)
const fs=require("fs"),path=require("path");
const LAZY=["culture","energie","populism","compta2","uspop","gastro","ukculture","startups","brands","barcelona","finance","econ","strategy","jargon","bigtech"];   // socio is the default quiz: it stays in the first load
const root=path.join(__dirname,"..");
const meta={};
for(const id of LAZY){
  global.window={};require(path.join(root,"js/banks/"+id+".js"));
  const b=window["BANK_"+id.toUpperCase()];
  meta[id]={group:b.group||"",title:b.title,subject:b.subject,kw:b.kw,sess:b.sess,tags:b.tags,sheet:fs.existsSync(path.join(root,"js/sheets/"+id+".js"))};
}
const out="// GENERATED by tools/build-catalog.js, do not edit by hand. Listing data for the quizzes whose files load on demand (js/banks/<id>.js, js/sheets/<id>.js).\nwindow.BANK_META="+JSON.stringify(meta)+";\n";
const f=path.join(root,"js/catalog.js");
if(process.argv.includes("--check")){const cur=fs.existsSync(f)?fs.readFileSync(f,"utf8"):"";if(cur!==out){console.error("js/catalog.js is out of date: run node tools/build-catalog.js");process.exit(1)}console.log("catalog ok")}
else{fs.writeFileSync(f,out);console.log("wrote",f,out.length,"bytes")}
