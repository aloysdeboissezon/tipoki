// Writes supabase/migrations/add_nick_filter.sql from the word lists in js/nickfilter.js, so the page and the database refuse the same names.
// Usage: node tools/gen-nick-sql.js   (tests/nickname.spec.js fails when the SQL file is out of date)
const fs=require("fs"),path=require("path");
const N=require("../js/nickfilter.js");
const out=path.join(__dirname,"..","supabase","migrations","add_nick_filter.sql");
const lat=N.TOKEN.filter(w=>!/[ㄱ-힣]/.test(w));
const T="^(?:"+lat.map(N.stretch).join("|")+")(?:s|es)?$",S=N.SUB.map(N.stretch).join("|"),K=N.KO.join("|");
const LEET={"0":"o","1":"i","3":"e","4":"a","5":"s","7":"t","@":"a","$":"s","!":"i","+":"t","|":"i","€":"e","£":"e","а":"a","е":"e","о":"o","с":"c","р":"p","х":"x","і":"i"};
const from=Object.keys(LEET).join(""),to=Object.values(LEET).join("");
const sql=`-- Nickname filter (generated by tools/gen-nick-sql.js from js/nickfilter.js: do not edit by hand).
-- Run once in the Supabase SQL editor. After it, the database refuses offensive names, links, e-mails and phone numbers
-- in players.nick (multiplayer rooms) and quietly shows "Player" for them on the league board, even when the page is bypassed.

create or replace function public.tpk_nick_check(p text) returns text
language plpgsql immutable set search_path = public as $$
declare
  raw text; v text; flat text; tok text; run text := ''; toks text[]; outt text[] := '{}'; part text;
begin
  raw := lower(regexp_replace(btrim(coalesce(p, '')), '[\\u200b-\\u200f\\u2028-\\u202f\\u2060\\ufeff]', '', 'g'));
  raw := regexp_replace(raw, '\\s+', ' ', 'g');
  if raw = '' then return ''; end if;
  if raw ~ 'https?:|www\\.|[a-z0-9]@[a-z0-9]|\\.(com|net|org|fr|es|io|eu|co|me|ly|gg|tv|xyz|app|link|ru|cn)([^a-z]|$)' or raw ~ '[0-9]([ .-]?[0-9]){6,}' then return 'link'; end if;
  v := translate(raw, 'àáâãäåçèéêëìíîïñòóôõöùúûüýÿ', 'aaaaaaceeeeiiiinooooouuuuyy');
  v := replace(replace(replace(replace(v, 'ß', 'ss'), 'ø', 'o'), 'æ', 'ae'), 'œ', 'oe');
  v := translate(v, '${from}', '${to}');
  flat := regexp_replace(v, '[^a-z0-9ㄱ-ㆎ가-힣]+', '', 'g');
  if flat ~ '${K}' then return 'bad'; end if;
  toks := array_remove(regexp_split_to_array(v, '[^a-z0-9ㄱ-ㆎ가-힣]+'), '');
  foreach tok in array coalesce(toks, '{}') loop
    part := tok;
${N.ALLOW.map(w=>`    part := replace(part, '${w}', ' ');`).join("\n")}
    outt := outt || array_remove(string_to_array(part, ' '), '');
    if length(tok) = 1 then run := run || tok;
    else
      if length(run) > 1 then outt := outt || run; end if;
      run := '';
    end if;
  end loop;
  if length(run) > 1 then outt := outt || run; end if;
  foreach tok in array outt loop
    if tok ~ '${T}' or tok ~ '${S}' then return 'bad'; end if;
  end loop;
  return '';
end $$;

create or replace function public.tpk_nick_ok(p text) returns boolean
language sql immutable set search_path = public as $$ select public.tpk_nick_check(p) = '' $$;

-- players: refuse a new or changed offensive name (names saved before this migration are shown as "Player" by the page)
create or replace function public.tpk_guard_players() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if length(coalesce(new.nick, '')) > 24 then raise exception 'bad_nick'; end if;
  if (tg_op = 'INSERT' or new.nick is distinct from old.nick) and not public.tpk_nick_ok(new.nick) then raise exception 'bad_nick'; end if;
  if new.ans is not null and octet_length(new.ans::text) > 20000 then raise exception 'too_big'; end if;
  if new.avatar is not null and length(new.avatar) > 100000 then raise exception 'too_big'; end if;
  if tg_op = 'INSERT' then
    if (select count(*) from players where code = new.code) >= 100 then raise exception 'room_full'; end if;
    if (select count(*) from players where created_at > now() - interval '1 hour') >= 6000 then raise exception 'slow_down'; end if;
  end if;
  return new;
end $$;

-- league: an offensive name becomes "Player"
`;
