// Builds the ESADE quiz "acct3" (Accounting test 3: financial statement analysis) from the exam-lab page script js/quiz-compta.js,
// so the question bank, the 20 mock tests and the cheat sheet stay written in one place.
// Usage: node tools/build-acct3.js        (needs Playwright, only to read the cheat-sheet HTML into study-sheet blocks)
// Writes api/_esade/banks/acct3.js (questions, mock exams, flashcards) and api/_esade/sheets/acct3.js (study sheet).
// The output is static (the page's seeded random numbers are frozen here), so every device builds the same quiz for multiplayer.
const fs=require("fs"),path=require("path"),root=path.join(__dirname,"..");
const src=fs.readFileSync(path.join(root,"js/quiz-compta.js"),"utf8");
// keep the data part of the page script: everything before the UI state, minus the two DOM lookups
const data=src.slice(0,src.indexOf("let state=")).replace(/^const \$=.*$/m,"").replace(/^const view=.*$/m,"");
const L=new Function(data+";return {OV,LQ,LT,PR,MK,NEW,TESTS,STARTER,SHEET,TIPS}")();
const S={Overview:1,Liquidity:2,"Long-term debt":3,Profitability:4,Market:5};
const SESS={1:"Overview: vertical, horizontal & limits",2:"Liquidity",3:"Long-term debt-paying ability",4:"Profitability",5:"Market ratios"};
const TAGS={1:"Overview",2:"Liquidity",3:"Long-term debt",4:"Profitability",5:"Market"};
const all=[L.OV,L.LQ,L.LT,L.PR,L.MK,...L.NEW].flat(),Q=[],TQ=[],ref=new Map();
const dec=x=>{const s=String(x);return s.includes(".")?s.split(".")[1].length:0};
// accepted typed answers: every value within the page's tolerance, at the precision of the answer
function variants(a,tol){let st=Math.pow(10,-Math.max(dec(a),dec(tol)));while(2*tol/st>40)st*=10;
  const out=new Set([String(a)]);for(let v=a-tol-1e-9;v<=a+tol+1e-9;v+=st){const r=Math.round(v/st)*st;if(Math.abs(r-a)<=tol+1e-9){const f=r.toFixed(Math.max(0,-Math.round(Math.log10(st))));out.add(f);out.add(String(+f))}}
  return [...out]}
for(const q of all){if(ref.has(q))continue;const s=S[q.t];if(!s)throw new Error("topic "+q.t);
  if(q.type==="mcq"){ref.set(q,{m:Q.length});Q.push({s,t:"",q:q.q,o:[q.opts[q.a],...q.opts.filter((x,i)=>i!==q.a)],a:0,e:q.exp,d:2})}
  else{ref.set(q,{t:TQ.length});TQ.push({s,q:q.q+(q.unit&&q.unit!=="x"&&!q.q.includes("("+q.unit)?" Answer in "+q.unit+".":""),a:variants(q.a,q.tol).concat(q.unit==="days"||q.unit==="years"?[q.a+" "+q.unit]:[]),num:[q.a,+Math.max(q.tol,Math.abs(q.a)*0.03).toFixed(4)],e:q.exp,d:3})}}
const EXAMS=L.TESTS.map(t=>({n:t.n,t:t.t,min:13,items:t.ix.map(q=>ref.get(q))}));
(async()=>{
  const {chromium}=require("playwright");const b=await chromium.launch();const p=await b.newPage();
  const parsed=await p.evaluate(html=>{
    const box=document.createElement("div");box.innerHTML=html;const txt=e=>e.innerHTML.trim();
    const sections=[],facts=[];
    for(const card of box.querySelectorAll(":scope > .card")){
      const h=card.querySelector("h2"),sec={title:h.innerHTML.replace(/^\d+\s*·\s*/,""),blocks:[]};
      const walk=el=>{for(const c of el.children){
        if(c===h)continue;const tag=c.tagName;
        if(c.classList.contains("tw"))walk(c);
        else if(tag==="P")sec.blocks.push({t:"p",x:txt(c)});
        else if(tag==="H3")sec.blocks.push({t:"h3",x:txt(c)});
        else if(tag==="UL"||tag==="OL")sec.blocks.push({t:tag.toLowerCase(),items:[...c.children].map(txt)});
        else if(c.classList.contains("rule"))sec.blocks.push({t:"key",title:c.classList.contains("warn")?"Watch out":"Rule",items:[txt(c)]});
        else if(tag==="TABLE"){const rows=[...c.querySelectorAll("tr")].map(r=>[...r.children]);
          if(rows[0]&&rows[0][0].tagName==="TH")sec.blocks.push({t:"table",head:rows[0].map(txt),rows:rows.slice(1).map(r=>r.map(txt))});
          else sec.blocks.push({t:"dl",items:rows.map(r=>r.map(txt))});
          const hd=rows[0]&&rows[0].map(x=>x.textContent.trim());
          if(hd&&hd[0]==="Measure")rows.slice(1).forEach(r=>facts.push({sec:sec.title,k:r[0].textContent.trim(),v:r[1].textContent.trim()}));
          if(sec.title==="Glossary")rows.forEach(r=>facts.push({sec:"Glossary",k:r[0].textContent.trim(),v:r[1].textContent.trim()}))}
        else sec.blocks.push({t:"p",x:c.outerHTML})}};
      walk(card);sections.push(sec)}
    return {sections,facts}},L.STARTER+L.SHEET+L.TIPS);
  await b.close();
  const secOf={Glossary:1,"Liquidity":2,"Long-term debt-paying ability":3,"Profitability":4,"Market ratios":5};
  const FACTS=parsed.facts.map(f=>[secOf[f.sec]||1,"fa","c",f.k,f.v]);
  const J=x=>JSON.stringify(x);
  const head="// GENERATED by tools/build-acct3.js from js/quiz-compta.js (the Financial Analysis Exam Lab page), do not edit by hand.\n";
  fs.writeFileSync(path.join(root,"api/_esade/banks/acct3.js"),head+
`// Accounting test 3: financial statement analysis (ratios), English. ${Q.length} MCQ + ${TQ.length} numeric questions, ${EXAMS.length} mock exams of 5 questions (13 min, scored +2 / −0.5 / 0 at the real exam).
window.BANK_ACCT3=(function(){
const SESS=${J(SESS)};
const TAGS=${J(TAGS)};
const Q=${J(Q)};
const TQ=${J(TQ)};
const FACTS=${J(FACTS)};
// mock exams: m = index in Q, t = index in TQ; the exam screen offers them next to the random exam
const EXAMS=${J(EXAMS)};
return {id:"acct3",group:"esade",title:"Accounting test 3",kw:"accounting compta financial analysis financial statement analysis ratios liquidity solvency debt profitability ROA ROE DuPont market EPS P/E mock exam esade quiz compta 3",subject:"Financial statement analysis: liquidity, long-term debt, profitability and market ratios, with 20 mock exams",lang:"en",sess:SESS,tags:TAGS,unit:["topic","topics","a topic"],balance:true,Q,TQ,facts:FACTS,noExpand:true,exams:EXAMS,examRule:{right:2,wrong:-0.5,max:10}};
})();
`);
  const sheet={lang:"en",file:"study-sheet-financial-analysis",tag:"Study sheet · Financial analysis",title:"Financial statement<br>analysis",
    sub:"Every ratio of the course with its formula and benchmark, one worked company, the direction questions, the traps and the 13-minute exam tactics.",
    source:"Financial Analysis Exam Lab · cheat sheet and exam tactics",
    intro:"Financial statement analysis turns the numbers of the statements into <b>ratios</b> that answer four questions: can the firm pay its bills (<b>liquidity</b>), carry its debt (<b>long-term debt</b>), earn from its sales and assets (<b>profitability</b>), and how does the market value it (<b>market ratios</b>)?",
    sections:parsed.sections};
  fs.writeFileSync(path.join(root,"api/_esade/sheets/acct3.js"),head+"window.SHEETS=window.SHEETS||{};\nwindow.SHEETS.acct3="+J(sheet)+";\n");
  console.log("acct3:",Q.length,"MCQ",TQ.length,"typed",FACTS.length,"cards",EXAMS.length,"exams",parsed.sections.length,"sheet sections");
})();
